/**
 * Trigger browser CSV download for procurement orders report.
 */
export function exportProcurementCsv(orders) {
  const headers = [
    'Order Ref',
    'Farmer',
    'Location',
    'Product',
    'Agreed Qty',
    'Weighed Qty',
    'Unit',
    'Agreed Price (INR)',
    'Total Amount (INR)',
    'Payment Arrangement',
    'Payment Status',
    'Order Status',
  ]
  const escape = (val) => `"${String(val ?? '').replaceAll('"', '""')}"`
  const rows = orders.map((o) => [
    o.orderRef,
    o.farmerName,
    o.farmerLocation,
    o.productName,
    o.agreedQuantity,
    o.weighedQuantity ?? o.agreedQuantity,
    o.unit,
    o.agreedPrice,
    o.totalAmount,
    o.paymentArrangement,
    o.paymentStatus,
    o.status,
  ])
  const csv = [headers, ...rows].map((r) => r.map(escape).join(',')).join('\n')
  const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = `farmlink-procurement-report-${new Date().toISOString().slice(0, 10)}.csv`
  link.click()
  URL.revokeObjectURL(url)
}

/**
 * Compute price variance and savings pill styling relative to a farmer's asking price.
 */
export function getOfferSpread(offeredPrice, askingPrice) {
  const offer = Number(offeredPrice) || 0
  const ask = Number(askingPrice) || 0
  if (!ask) {
    return { diff: 0, pct: 0, text: 'At ask', cls: 'bg-slate-100 text-slate-600 border-slate-200' }
  }
  const diff = offer - ask
  const pct = Math.round((diff / ask) * 100)
  if (diff < 0) {
    return {
      diff,
      pct,
      text: `${pct}% vs ask`,
      cls: 'bg-emerald-50 text-emerald-700 border-emerald-200',
    }
  }
  if (diff === 0) {
    return {
      diff: 0,
      pct: 0,
      text: 'At ask',
      cls: 'bg-slate-100 text-slate-600 border-slate-200',
    }
  }
  return {
    diff,
    pct,
    text: `+${pct}% vs ask`,
    cls: 'bg-rose-50 text-rose-700 border-rose-200',
  }
}

